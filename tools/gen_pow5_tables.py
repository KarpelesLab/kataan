#!/usr/bin/env python3
"""Generate `src/realm/pow5_tables.rs`: the 128-bit power-of-five tables the
shortest double-to-decimal conversion in `src/realm/ryu.rs` multiplies by.

Usage:

    tools/gen_pow5_tables.py > src/realm/pow5_tables.rs

The tables follow the description in Ulf Adams, "Ryu: Fast Float-to-String
Conversion" (PLDI 2018), section 3: for a double, values are scaled by a
power of five held to `B = 125` significant bits.

- `POW5[i]`, `0 <= i < 326`: `5^i` normalized to its top 125 bits,
  `floor(5^i / 2^(bitlen(5^i) - 125))` (shifted left when shorter).
- `POW5_INV[q]`, `0 <= q < 342`: `floor(2^(bitlen(5^q) - 1 + 125) / 5^q) + 1`,
  the rounded-up reciprocal at the same precision.

Each entry is emitted as `(low 64 bits, high 64 bits)`.
"""

B = 125
N_POW5 = 326
N_POW5_INV = 342


def split(v):
    assert 0 <= v < 1 << 128
    return v & ((1 << 64) - 1), v >> 64


def main():
    out = []
    out.append("//! 128-bit power-of-five tables for the shortest double-to-decimal")
    out.append("//! conversion (`super::ryu`).")
    out.append("//!")
    out.append("//! @generated by `tools/gen_pow5_tables.py` -- DO NOT EDIT. Regenerate with:")
    out.append("//!")
    out.append("//! ```text")
    out.append("//! tools/gen_pow5_tables.py > src/realm/pow5_tables.rs")
    out.append("//! ```")
    out.append("")
    out.append("/// `5^i` to its top 125 bits, as `(low, high)` 64-bit halves.")
    out.append("pub(super) static POW5: [(u64, u64); %d] = [" % N_POW5)
    for i in range(N_POW5):
        p = 5 ** i
        j = p.bit_length() - B
        v = p >> j if j >= 0 else p << -j
        lo, hi = split(v)
        out.append("    (0x%016x, 0x%016x)," % (lo, hi))
    out.append("];")
    out.append("")
    out.append("/// `floor(2^(bitlen(5^q) - 1 + 125) / 5^q) + 1`, as `(low, high)` 64-bit halves.")
    out.append("pub(super) static POW5_INV: [(u64, u64); %d] = [" % N_POW5_INV)
    for q in range(N_POW5_INV):
        p = 5 ** q
        j = p.bit_length() - 1 + B
        v = (1 << j) // p + 1
        lo, hi = split(v)
        out.append("    (0x%016x, 0x%016x)," % (lo, hi))
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
