#!/usr/bin/env python3
"""Generate `src/regex/fold_data.rs` -- Unicode *simple* case folding (`scf`),
the `Canonicalize` of a `u`/`v`-mode case-insensitive regex (ECMA-262
22.2.2.7.3).

Usage:

    tools/gen_unicode_fold.py <ucd-dir> > src/regex/fold_data.rs

`<ucd-dir>` must contain `CaseFolding.txt`, downloaded from
https://www.unicode.org/Public/<version>/ucd/ .

Simple case folding is the file's mappings with status `C` (common) and `S`
(simple); `F` (full, multi-character) and `T` (Turkic) entries are excluded.
Every code point absent from the table folds to itself. The table is emitted
twice: sorted by source (to compute `scf(c)`) and sorted by target (to list the
code points that fold *onto* a given one -- the rest of `c`'s equivalence
class, which a property or range member may hit even when `c` itself is not in
the set).
"""

import os
import sys

UNICODE_VERSION = "17.0.0"


def parse(path):
    pairs = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            code, status, mapping = fields[0], fields[1], fields[2]
            if status not in ("C", "S"):
                continue
            targets = mapping.split()
            assert len(targets) == 1, line
            pairs.append((int(code, 16), int(targets[0], 16)))
    return pairs


def emit_table(out, name, doc, pairs):
    out.append(doc)
    out.append(f"pub(super) static {name}: &[(u32, u32)] = &[")
    row = []
    for a, b in pairs:
        row.append(f"(0x{a:04X}, 0x{b:04X})")
        if len(row) == 6:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    out.append("];")
    out.append("")


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_unicode_fold.py <ucd-dir>")
    pairs = parse(os.path.join(sys.argv[1], "CaseFolding.txt"))
    by_source = sorted(pairs)
    by_target = sorted(pairs, key=lambda p: (p[1], p[0]))
    sources = [a for a, _ in by_source]
    assert len(set(sources)) == len(sources), "duplicate C/S source"
    out = [
        "//! Unicode simple case folding (`scf`) for case-insensitive `u`/`v` regexes.",
        "//!",
        f"//! @generated by `tools/gen_unicode_fold.py` from the Unicode {UNICODE_VERSION}",
        "//! `CaseFolding.txt` (statuses C and S) -- DO NOT EDIT. Regenerate with:",
        "//!",
        "//! ```text",
        "//! tools/gen_unicode_fold.py <ucd-dir> > src/regex/fold_data.rs",
        "//! ```",
        "",
    ]
    emit_table(
        out,
        "SCF_BY_SOURCE",
        "/// `(c, scf(c))` for every code point that does not fold to itself, sorted by `c`.",
        by_source,
    )
    emit_table(
        out,
        "SCF_BY_TARGET",
        "/// The same pairs sorted by `(scf(c), c)`: the code points folding onto a target.",
        by_target,
    )
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
